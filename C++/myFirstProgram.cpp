#include <iostream>
using namespace std;

int main() {
    int x = 6;
    int y = 3;

    //Arithmetic Operators
    
    cout << (x + y) << "\n";    //addition
    cout << (x - y) << "\n";    //subtraction
    cout << (x * y) << "\n";    //multiplication
    cout << (x / y) << "\n";    //division
    cout << (x % y) << "\n";    //modulus

    return 0;
}